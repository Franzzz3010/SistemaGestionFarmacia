    private void btnRegistrarCompraActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarCompraActionPerformed
        try {

        if (cmbProveedor.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione un proveedor."
            );
            return;
        }

        DefaultTableModel modelo =
                (DefaultTableModel) tblDetalleCompra.getModel();

        if (modelo.getRowCount() == 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "Agregue al menos un medicamento a la compra."
            );
            return;
        }

        String seleccionProveedor =
                cmbProveedor.getSelectedItem().toString();

        int idProveedor = Integer.parseInt(
                seleccionProveedor.split(" - ", 2)[0].trim()
        );

        LocalDate fecha = LocalDate.parse(
                txtFecha.getText().trim()
        );

        Date fechaCompra = java.sql.Date.valueOf(fecha);

        List<DetalleCompra> detalles = new ArrayList<>();

        double total = 0;

        for (int i = 0; i < modelo.getRowCount(); i++) {

            int idMedicamento =
                    ((Number) modelo.getValueAt(i, 0)).intValue();

            int cantidad =
                    ((Number) modelo.getValueAt(i, 2)).intValue();

            double costo =
                    ((Number) modelo.getValueAt(i, 3)).doubleValue();

            if (idMedicamento <= 0 || cantidad <= 0
                    || !Double.isFinite(costo) || costo < 0) {
                throw new IllegalArgumentException(
                        "Hay medicamentos con datos inválidos."
                );
            }

            total += cantidad * costo;

            DetalleCompra detalle = new DetalleCompra(
                    0,
                    0,
                    idMedicamento,
                    cantidad,
                    costo
            );

            detalles.add(detalle);
        }

        if (!Double.isFinite(total)) {
            throw new IllegalArgumentException(
                    "El total de la compra no es válido."
            );
        }

        Compra compra = new Compra(
                0,
                fechaCompra,
                total,
                idProveedor
        );

        int confirmacion = JOptionPane.showConfirmDialog(
                this,
                "¿Desea registrar esta compra?\n"
                + "Medicamentos: " + detalles.size() + "\n"
                + "Total: Q"
                + String.format(java.util.Locale.US, "%.2f", total),
                "Confirmar compra",
                JOptionPane.YES_NO_OPTION
        );

        if (confirmacion != JOptionPane.YES_OPTION) {
            return;
        }

        RegistroCompraDatos registro = new RegistroCompraDatos();

        int idCompra = registro.registrarCompra(compra, detalles);

        JOptionPane.showMessageDialog(
                this,
                "Compra registrada correctamente.\n"
                + "ID de compra: " + idCompra + "\n"
                + "Total: Q"
                + String.format(java.util.Locale.US, "%.2f", total)
                + "\nInventario actualizado."
        );

        limpiarCompra();

    } catch (DateTimeParseException e) {

        JOptionPane.showMessageDialog(
                this,
                "Ingrese una fecha válida con formato yyyy-MM-dd."
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Hay un ID o valor numérico inválido."
        );

    } catch (IllegalArgumentException e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Datos inválidos",
                JOptionPane.WARNING_MESSAGE
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "No se pudo registrar la compra.\n"
                + "No se confirmaron los cambios.\n\n"
                + "Detalle: " + e.getMessage(),
                "Error de base de datos",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnRegistrarCompraActionPerformed

