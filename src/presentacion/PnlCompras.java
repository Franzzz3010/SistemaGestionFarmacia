private void calcularTotal() {

    double total = 0;

    DefaultTableModel modelo =
            (DefaultTableModel) tblDetalleCompra.getModel();

    for (int i = 0; i < modelo.getRowCount(); i++) {

        total += ((Number) modelo.getValueAt(i, 4))
                .doubleValue();
    }

    txtTotal.setText(
            String.format(java.util.Locale.US, "%.2f", total)
    );
}

private void limpiarCompra() {

    txtIdCompra.setText("");

    txtFecha.setText(
            java.time.LocalDate.now().toString()
    );

    cmbProveedor.setSelectedIndex(0);
    cmbMedicamento.setSelectedIndex(0);

    txtCantidad.setText("");
    txtCosto.setText("");

    DefaultTableModel modelo =
            (DefaultTableModel) tblDetalleCompra.getModel();

    modelo.setRowCount(0);

    calcularTotal();

    tblDetalleCompra.clearSelection();
}

