    private void btnAgregarDetalleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarDetalleActionPerformed
           try {

        if (cmbMedicamento.getSelectedIndex() <= 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione un medicamento."
            );
            return;
        }

        String seleccion =
                cmbMedicamento.getSelectedItem().toString();

        int idMedicamento = Integer.parseInt(
                seleccion.split(" - ", 2)[0].trim()
        );

        String nombreMedicamento =
                seleccion.split(" - ", 2)[1];

        int cantidad = Integer.parseInt(
                txtCantidad.getText().trim()
        );

        double costo = Double.parseDouble(
                txtCosto.getText().trim()
        );

        if (cantidad <= 0 || !Double.isFinite(costo) || costo < 0) {
            JOptionPane.showMessageDialog(
                    this,
                    "La cantidad debe ser mayor que cero "
                    + "y el costo debe ser válido y no negativo."
            );
            return;
        }

        DefaultTableModel modelo =
                (DefaultTableModel) tblDetalleCompra.getModel();

        for (int i = 0; i < modelo.getRowCount(); i++) {

            int idExistente = ((Number)
                    modelo.getValueAt(i, 0)).intValue();

            if (idExistente == idMedicamento) {
                JOptionPane.showMessageDialog(
                        this,
                        "Este medicamento ya está agregado."
                );
                return;
            }
        }

        double subtotal = cantidad * costo;

        if (!Double.isFinite(subtotal)) {
            throw new IllegalArgumentException(
                    "El subtotal es demasiado grande."
            );
        }

        modelo.addRow(new Object[]{
            idMedicamento,
            nombreMedicamento,
            cantidad,
            costo,
            subtotal
        });

        calcularTotal();

        cmbMedicamento.setSelectedIndex(0);
        txtCantidad.setText("");
        txtCosto.setText("");

        JOptionPane.showMessageDialog(
                this,
                "Medicamento agregado a la compra."
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Ingrese una cantidad entera y un costo numérico válido."
        );

    } catch (IllegalArgumentException e) {

        JOptionPane.showMessageDialog(
                this,
                e.getMessage()
        );
    }
    }//GEN-LAST:event_btnAgregarDetalleActionPerformed

    private void btnQuitarDetalleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarDetalleActionPerformed
        int filaSeleccionada = tblDetalleCompra.getSelectedRow();

    if (filaSeleccionada == -1) {
        JOptionPane.showMessageDialog(
                this,
                "Seleccione un medicamento de la tabla para quitarlo."
        );
        return;
    }

    int confirmacion = JOptionPane.showConfirmDialog(
            this,
            "¿Desea quitar este medicamento de la compra?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION
    );

    if (confirmacion == JOptionPane.YES_OPTION) {

        DefaultTableModel modelo =
                (DefaultTableModel) tblDetalleCompra.getModel();

        int filaModelo = tblDetalleCompra.convertRowIndexToModel(
                filaSeleccionada
        );

        modelo.removeRow(filaModelo);

        calcularTotal();

        JOptionPane.showMessageDialog(
                this,
                "Medicamento quitado correctamente."
        );
    }
    }//GEN-LAST:event_btnQuitarDetalleActionPerformed

