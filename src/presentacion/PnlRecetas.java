    private void tblRecetasMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblRecetasMouseClicked
        int fila = tblRecetas.getSelectedRow();

if (fila >= 0) {

    int filaModelo = tblRecetas.convertRowIndexToModel(fila);

    int idReceta = Integer.parseInt(
            tblRecetas.getModel().getValueAt(filaModelo, 0).toString()
    );

    RecetaMedicaDAO dao = new RecetaMedicaDAO();

    for (RecetaMedica receta : dao.listar()) {

        if (receta.getIdReceta() == idReceta) {

            txtIdReceta.setText(
                    String.valueOf(receta.getIdReceta())
            );

            for (int i = 0; i < cmbCliente.getItemCount(); i++) {

                String cliente = cmbCliente.getItemAt(i).toString();

                if (cliente.startsWith(receta.getIdCliente() + " - ")) {
                    cmbCliente.setSelectedIndex(i);
                    break;
                }
            }

            txtMedico.setText(receta.getMedico());

            txtFecha.setText(
                    receta.getFecha().toString()
            );

            txtMedicamentos.setText(
                    receta.getMedicamentosAutorizados()
            );

            break;
        }
    }
}
    }//GEN-LAST:event_tblRecetasMouseClicked

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {

    if (cmbCliente.getSelectedItem() == null) {
        throw new IllegalArgumentException(
                "Debe seleccionar un cliente.");
    }

    String medico = txtMedico.getText().trim();
    String fechaTexto = txtFecha.getText().trim();
    String medicamentos = txtMedicamentos.getText().trim();

    if (medico.isEmpty() || fechaTexto.isEmpty()
            || medicamentos.isEmpty()) {
        throw new IllegalArgumentException(
                "Debe completar todos los campos.");
    }

    String clienteSeleccionado =
            cmbCliente.getSelectedItem().toString();

    int idCliente = Integer.parseInt(
            clienteSeleccionado.split(" - ", 2)[0].trim()
    );

    java.sql.Date fecha = java.sql.Date.valueOf(fechaTexto);

    RecetaMedica receta = new RecetaMedica();

    receta.setIdCliente(idCliente);
    receta.setMedico(medico);
    receta.setFecha(fecha);
    receta.setMedicamentosAutorizados(medicamentos);

    RecetaMedicaDAO dao = new RecetaMedicaDAO();

    if (dao.insertar(receta)) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Receta médica guardada correctamente.");

        cargarRecetas();

        txtIdReceta.setText("");
        cmbCliente.setSelectedIndex(-1);
        txtMedico.setText("");
        txtFecha.setText(
    java.time.LocalDate.now().toString()
);
        txtMedicamentos.setText("");

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this, "No se pudo guardar la receta.");
    }

} catch (IllegalArgumentException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this, "Verifica los datos: " + e.getMessage());

}
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        try {

    if (txtIdReceta.getText().trim().isEmpty()) {
        throw new IllegalArgumentException(
                "Debe seleccionar una receta de la tabla.");
    }

    if (cmbCliente.getSelectedItem() == null) {
        throw new IllegalArgumentException(
                "Debe seleccionar un cliente.");
    }

    String medico = txtMedico.getText().trim();
    String medicamentos = txtMedicamentos.getText().trim();

    if (medico.isEmpty() || medicamentos.isEmpty()) {
        throw new IllegalArgumentException(
                "Debe completar todos los campos.");
    }

    int idReceta = Integer.parseInt(
            txtIdReceta.getText().trim()
    );

    String clienteSeleccionado =
            cmbCliente.getSelectedItem().toString();

    int idCliente = Integer.parseInt(
            clienteSeleccionado.split(" - ", 2)[0].trim()
    );

    java.sql.Date fecha = java.sql.Date.valueOf(
            txtFecha.getText().trim()
    );

    RecetaMedica receta = new RecetaMedica();

    receta.setIdReceta(idReceta);
    receta.setIdCliente(idCliente);
    receta.setMedico(medico);
    receta.setFecha(fecha);
    receta.setMedicamentosAutorizados(medicamentos);

    RecetaMedicaDAO dao = new RecetaMedicaDAO();

    int confirmar = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Desea actualizar esta receta médica?",
            "Confirmar edición",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (confirmar == javax.swing.JOptionPane.YES_OPTION) {

        if (dao.actualizar(receta)) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Receta médica actualizada correctamente."
            );

            cargarRecetas();

            txtIdReceta.setText("");
            cmbCliente.setSelectedIndex(-1);
            txtMedico.setText("");
            txtFecha.setText(
                    java.time.LocalDate.now().toString()
            );
            txtMedicamentos.setText("");

            tblRecetas.clearSelection();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "No se pudo actualizar la receta médica."
            );
        }
    }

} catch (IllegalArgumentException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Verifica los datos: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnEditarActionPerformed

