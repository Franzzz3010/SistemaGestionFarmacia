private void cargarClientes() {

    cmbCliente.removeAllItems();

    ClienteDAO dao = new ClienteDAO();
    List<Cliente> clientes = dao.listar();

    for (Cliente cliente : clientes) {
        cmbCliente.addItem(
            cliente.getIdCliente() + " - " + cliente.getNombre()
        );
    }

    cmbCliente.setSelectedIndex(-1);
}
private void cargarRecetas() {

    DefaultTableModel modelo = new DefaultTableModel();

    modelo.addColumn("ID Receta");
    modelo.addColumn("Cliente");
    modelo.addColumn("Médico");
    modelo.addColumn("Fecha");
    modelo.addColumn("Medicamentos autorizados");

    RecetaMedicaDAO dao = new RecetaMedicaDAO();

    for (RecetaMedica receta : dao.listar()) {

        String nombreCliente = "ID: " + receta.getIdCliente();

        for (Cliente cliente : new ClienteDAO().listar()) {

            if (cliente.getIdCliente() == receta.getIdCliente()) {
                nombreCliente = cliente.getNombre();
                break;
            }
        }

        modelo.addRow(new Object[]{
            receta.getIdReceta(),
            nombreCliente,
            receta.getMedico(),
            receta.getFecha(),
            receta.getMedicamentosAutorizados()
        });
    }

    tblRecetas.setModel(modelo);
}
