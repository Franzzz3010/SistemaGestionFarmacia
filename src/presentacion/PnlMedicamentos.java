    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
         try {

        String nombre = txtNombre.getText().trim();
        String presentacion = label.getText().trim();
        String textoPrecio = txtPrecio.getText().trim();
        String textoExistencia = txtExistencia.getText().trim();

        if (nombre.isEmpty() || presentacion.isEmpty()
                || textoPrecio.isEmpty() || textoExistencia.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Complete todos los campos obligatorios."
            );
            return;
        }

        if (cmbCategoria.getSelectedIndex() <= 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione una categoría."
            );
            return;
        }

        double precio = Double.parseDouble(textoPrecio);
        int existencia = Integer.parseInt(textoExistencia);

        if (!Double.isFinite(precio) || precio <= 0 || existencia < 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "El precio debe ser mayor que cero y la existencia no puede ser negativa."
            );
            return;
        }

        boolean requiereReceta = chkRequiereReceta.isSelected();

        String categoriaSeleccionada =
                cmbCategoria.getSelectedItem().toString();

        int idCategoria = Integer.parseInt(
                categoriaSeleccionada.split(" - ", 2)[0].trim()
        );

        Medicamento medicamento = new Medicamento(
                0,
                nombre,
                presentacion,
                precio,
                existencia,
                requiereReceta,
                idCategoria
        );

        MedicamentoDatos datos = new MedicamentoDatos();

        if (datos.agregar(medicamento)) {

            JOptionPane.showMessageDialog(
                    this,
                    "Medicamento registrado correctamente."
            );

            cargarMedicamentos();

            txtIdMedicamento.setText("");
            txtNombre.setText("");
            label.setText("");
            txtPrecio.setText("");
            txtExistencia.setText("");

            chkRequiereReceta.setSelected(false);
            cmbCategoria.setSelectedIndex(0);

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo registrar el medicamento."
            );
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Ingrese un precio y una existencia válidos."
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error de base de datos: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void tblMedicamentosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMedicamentosMouseClicked
                int fila = tblMedicamentos.getSelectedRow();

    if (fila == -1) {
        return;
    }

    int filaModelo = tblMedicamentos.convertRowIndexToModel(fila);

    try {

        int idMedicamento = Integer.parseInt(
                tblMedicamentos.getModel()
                        .getValueAt(filaModelo, 0).toString()
        );

        MedicamentoDatos datos = new MedicamentoDatos();
        Medicamento medicamento = datos.buscar(idMedicamento);

        if (medicamento == null) {
            JOptionPane.showMessageDialog(
                    this,
                    "No se encontró el medicamento."
            );
            return;
        }

        txtIdMedicamento.setText(
                String.valueOf(medicamento.getIdMedicamento())
        );

        txtNombre.setText(medicamento.getNombre());
        txtPresentacion.setText(medicamento.getPresentacion());
        txtPrecio.setText(String.valueOf(medicamento.getPrecio()));
        txtExistencia.setText(String.valueOf(medicamento.getExistencia()));

        chkRequiereReceta.setSelected(
                medicamento.isRequiereReceta()
        );

        cmbCategoria.setSelectedIndex(0);

        for (int i = 1; i < cmbCategoria.getItemCount(); i++) {

            String categoria = cmbCategoria.getItemAt(i).toString();

            if (categoria.startsWith(
                    medicamento.getIdCategoria() + " - ")) {

                cmbCategoria.setSelectedIndex(i);
                break;
            }
        }

    } catch (java.sql.SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al seleccionar medicamento: " + e.getMessage(),
                "Error de base de datos",
                JOptionPane.ERROR_MESSAGE
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "El ID del medicamento no es válido."
        );
    }
    }//GEN-LAST:event_tblMedicamentosMouseClicked

