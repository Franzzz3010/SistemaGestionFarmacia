private void cargarMedicamentos() {
DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{
                "ID", "Nombre", "Presentación",
                "Precio", "Existencia",
                "Requiere receta", "Categoría"
            }, 0
    ) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };

    try {

        MedicamentoDatos datos = new MedicamentoDatos();

        for (Object[] fila : datos.listarConCategoria()) {
            modelo.addRow(fila);
        }

        tblMedicamentos.setModel(modelo);

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al cargar medicamentos: " + e.getMessage(),
                "Error de base de datos",
                JOptionPane.ERROR_MESSAGE
        );
    }
}
private void cargarCategorias() {

    DefaultComboBoxModel<String> modelo =
            new DefaultComboBoxModel<>();

    modelo.addElement("Seleccione una categoría");

    try {

        CategoriaMedicamentoDatos datos =
                new CategoriaMedicamentoDatos();

        for (CategoriaMedicamento categoria : datos.listar()) {
            modelo.addElement(
                    categoria.getIdCategoria() + " - " +
                    categoria.getNombre()
            );
        }

        cmbCategoria.setModel(modelo);
        cmbCategoria.setSelectedIndex(0);

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al cargar categorías: " + e.getMessage(),
                "Error de base de datos",
                JOptionPane.ERROR_MESSAGE
        );
    }
}
private void limpiarCampos() {

    txtIdMedicamento.setText("");
    txtNombre.setText("");
    txtPresentacion.setText("");
    txtPrecio.setText("");
    txtExistencia.setText("");

    chkRequiereReceta.setSelected(false);

    if (cmbCategoria.getItemCount() > 0) {
        cmbCategoria.setSelectedIndex(0);
    }

    tblMedicamentos.clearSelection();
    txtNombre.requestFocusInWindow();
}

