    private void cmbMedicamentoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbMedicamentoActionPerformed
 Medicamento medicamento =
            (Medicamento) cmbMedicamento.getSelectedItem();

    chkRecetaValidada.setSelected(false);
    chkRecetaValidada.setEnabled(false);

    if (medicamento != null) {

        txtPrecioUnitario.setText(
                String.format(java.util.Locale.US,
                        "%.2f", medicamento.getPrecio())
        );

        if (medicamento.isRequiereReceta()) {

            RecetaMedica receta =
        (RecetaMedica) cmbReceta.getSelectedItem();

Cliente cliente =
        (Cliente) cmbCliente.getSelectedItem();

boolean recetaDisponible =
        receta != null
        && cliente != null
        && receta.getIdCliente() == cliente.getIdCliente()
        && receta.getMedicamentosAutorizados() != null
        && !receta.getMedicamentosAutorizados().trim().isEmpty();

chkRecetaValidada.setEnabled(recetaDisponible);

            JOptionPane.showMessageDialog(
                    this,
                    "Este medicamento requiere receta médica.\n"
                    + "Seleccione la receta correspondiente al cliente,\n"
                    + "revise la prescripción y confirme su verificación.",
                    "Receta médica requerida",
                    JOptionPane.WARNING_MESSAGE
            );
        }

    } else {

        txtPrecioUnitario.setText("");
    }
    }//GEN-LAST:event_cmbMedicamentoActionPerformed

    private void btnAgregarMedicamentoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarMedicamentoActionPerformed
        try {

        Medicamento medicamento =
                (Medicamento) cmbMedicamento.getSelectedItem();

        if (medicamento == null) {
            JOptionPane.showMessageDialog(this,
                    "Seleccione un medicamento.");
            return;
        }
        if (medicamento.isRequiereReceta()) {

    Cliente cliente =
            (Cliente) cmbCliente.getSelectedItem();

    RecetaMedica receta =
            (RecetaMedica) cmbReceta.getSelectedItem();

    if (cliente == null || receta == null
            || receta.getIdCliente() != cliente.getIdCliente()) {

        JOptionPane.showMessageDialog(this,
                "Debe seleccionar una receta médica "
                + "correspondiente al cliente.");
        return;
    }

    if (receta.getMedicamentosAutorizados() == null
            || receta.getMedicamentosAutorizados().trim().isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "La receta no contiene medicamentos autorizados.");
        return;
    }

    if (!chkRecetaValidada.isSelected()) {

        JOptionPane.showMessageDialog(this,
                "Debe revisar la receta y confirmar "
                + "que el medicamento, presentación y cantidad "
                + "corresponden a la prescripción.");
        return;
    }
}
        int cantidad = Integer.parseInt(txtCantidad.getText().trim());

        if (cantidad <= 0) {
            JOptionPane.showMessageDialog(this,
                    "La cantidad debe ser mayor que cero.");
            return;
        }

        int cantidadAcumulada = cantidad;

        for (int i = 0; i < modeloDetalle.getRowCount(); i++) {

            int id = Integer.parseInt(
                    modeloDetalle.getValueAt(i, 0).toString());

            if (id == medicamento.getIdMedicamento()) {

                cantidadAcumulada += Integer.parseInt(
                        modeloDetalle.getValueAt(i, 2).toString());
            }
        }

        if (cantidadAcumulada > medicamento.getExistencia()) {
            JOptionPane.showMessageDialog(this,
                    "Existencia insuficiente.\nDisponibles: "
                    + medicamento.getExistencia());
            return;
        }

        double precio = medicamento.getPrecio();
        double subtotal = cantidad * precio;

        for (int i = 0; i < modeloDetalle.getRowCount(); i++) {

            int id = Integer.parseInt(
                    modeloDetalle.getValueAt(i, 0).toString());

           if (id == medicamento.getIdMedicamento()) {

    int nuevaCantidad = cantidadAcumulada;

    modeloDetalle.setValueAt(nuevaCantidad, i, 2);
    modeloDetalle.setValueAt(
            nuevaCantidad * precio, i, 4);
    
    cmbCliente.setEnabled(false);
    guardarRecetaVerificada(medicamento);

    calcularTotal();

    txtCantidad.setText("");
    chkRecetaValidada.setSelected(false);
    return;
}
        }

        modeloDetalle.addRow(new Object[]{
    medicamento.getIdMedicamento(),
    medicamento.getNombre(),
    cantidad,
    precio,
    subtotal
});
    cmbCliente.setEnabled(false);
guardarRecetaVerificada(medicamento);

calcularTotal();

txtCantidad.setText("");
    chkRecetaValidada.setSelected(false);

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Ingrese una cantidad numérica válida.");

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this,
                "Error al agregar medicamento: " + e.getMessage());
    }
    }//GEN-LAST:event_btnAgregarMedicamentoActionPerformed

    private void btnQuitarMedicamentoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarMedicamentoActionPerformed
        int fila = tblDetalleVenta.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this,
                "Seleccione un medicamento de la tabla.");
        return;
    }

    int confirmacion = JOptionPane.showConfirmDialog(
            this,
            "¿Desea quitar el medicamento seleccionado?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION
    );

    if (confirmacion == JOptionPane.YES_OPTION) {

        int filaModelo = tblDetalleVenta.convertRowIndexToModel(fila);

        modeloDetalle.removeRow(filaModelo);
        if (modeloDetalle.getRowCount() == 0) {
        cmbCliente.setEnabled(true);
}
        int idMedicamento = Integer.parseInt(
        modeloDetalle.getValueAt(filaModelo, 0).toString()
         );

        recetasVerificadas.remove(idMedicamento);
        cantidadesVerificadas.remove(idMedicamento);
        calcularTotal();
        
        JOptionPane.showMessageDialog(this,
                "Medicamento quitado correctamente.");
    }
    }//GEN-LAST:event_btnQuitarMedicamentoActionPerformed

    private void btnNuevaVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNuevaVentaActionPerformed
        if (modeloDetalle.getRowCount() > 0) {

        int confirmacion = JOptionPane.showConfirmDialog(
                this,
                "¿Desea iniciar una nueva venta?\n"
                + "Se perderán los medicamentos agregados.",
                "Confirmar nueva venta",
                JOptionPane.YES_NO_OPTION
        );

        if (confirmacion != JOptionPane.YES_OPTION) {
            return;
        }
    }

    modeloDetalle.setRowCount(0);
    cmbCliente.setEnabled(true);
    recetasVerificadas.clear();
    cantidadesVerificadas.clear();
    
    chkRecetaValidada.setSelected(false);
    chkRecetaValidada.setEnabled(false);
    txtIdVenta.setText("");
    txtFecha.setText(java.time.LocalDate.now().toString());
    txtCantidad.setText("");
    txtPrecioUnitario.setText("");
    txtTotal.setText("0.00");

    cmbCliente.setSelectedIndex(-1);    

    cargarMedicamentos();

    JOptionPane.showMessageDialog(this,
            "Formulario preparado para una nueva venta.");

    }//GEN-LAST:event_btnNuevaVentaActionPerformed

