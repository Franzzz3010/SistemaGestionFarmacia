private void cargarMedicamentos() {

    try {

        MedicamentoDatos datos = new MedicamentoDatos();

        cmbMedicamento.removeAllItems();

        for (Medicamento medicamento : datos.listar()) {

            if (medicamento.getExistencia() > 0) {
                cmbMedicamento.addItem(medicamento);
            }
        }

        cmbMedicamento.setSelectedIndex(-1);

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this,
                "Error al cargar medicamentos: " + e.getMessage());
    }
}
