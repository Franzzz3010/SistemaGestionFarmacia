    private void btnVerDetalleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerDetalleActionPerformed
int fila = tblHistorialCompras.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(
                this,
                "Seleccione una compra para ver sus detalles."
        );
        return;
    }

    int filaModelo =
            tblHistorialCompras.convertRowIndexToModel(fila);

    int idCompra = ((Number) tblHistorialCompras
            .getModel().getValueAt(filaModelo, 0)).intValue();

    DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{
                "Medicamento",
                "Cantidad",
                "Costo unitario",
                "Subtotal"
            }, 0
    ) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };

    String sql = """
        SELECT
            m.nombre AS medicamento,
            d.cantidad,
            d.costo,
            d.cantidad * d.costo AS subtotal
        FROM DetalleCompra d
        INNER JOIN Medicamento m
            ON d.idMedicamento = m.idMedicamento
        WHERE d.idCompra = ?
        ORDER BY d.idDetalleCompra
        """;

    try (Connection conexion = Conexion.conectar();
         PreparedStatement ps = conexion.prepareStatement(sql)) {

        ps.setInt(1, idCompra);

        try (ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {

                modelo.addRow(new Object[]{
                    rs.getString("medicamento"),
                    rs.getInt("cantidad"),
                    rs.getBigDecimal("costo"),
                    rs.getBigDecimal("subtotal")
                });
            }
        }

        JTable tablaDetalle = new JTable(modelo);
        tablaDetalle.setRowHeight(25);

        JScrollPane scroll = new JScrollPane(tablaDetalle);
        scroll.setPreferredSize(
                new java.awt.Dimension(650, 250)
        );

        JOptionPane.showMessageDialog(
                this,
                scroll,
                "Detalle de compra N.º " + idCompra,
                JOptionPane.INFORMATION_MESSAGE
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al consultar los detalles:\n"
                + e.getMessage(),
                "Error de base de datos",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnVerDetalleActionPerformed

    private void btnVolverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVolverActionPerformed
        java.awt.Container contenedor = getParent();

    while (contenedor != null
            && !"pnlContenido".equals(contenedor.getName())) {

        contenedor = contenedor.getParent();
    }

    if (contenedor instanceof javax.swing.JPanel) {

        javax.swing.JPanel panel =
                (javax.swing.JPanel) contenedor;

        panel.removeAll();

        panel.setLayout(new java.awt.BorderLayout());

        panel.add(
                new PnlCompras(),
                java.awt.BorderLayout.CENTER
        );

        panel.revalidate();
        panel.repaint();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "No se encontró el panel principal."
        );
    }
    }//GEN-LAST:event_btnVolverActionPerformed


private void cargarHistorialCompras() {


    DefaultTableModel modelo = new DefaultTableModel(
            new Object[]{
                "ID Compra",
                "Fecha",
                "Proveedor",
                "Total"
            }, 0
    ) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };

    String sql = """
        SELECT
            c.idCompra,
            c.fecha,
            p.nombre AS proveedor,
            c.total
        FROM Compra c
        INNER JOIN Proveedor p
            ON c.idProveedor = p.idProveedor
        ORDER BY c.idCompra DESC
        """;

    try (Connection conexion = Conexion.conectar();
         PreparedStatement ps = conexion.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {

            modelo.addRow(new Object[]{
                rs.getInt("idCompra"),
                rs.getDate("fecha"),
                rs.getString("proveedor"),
                rs.getBigDecimal("total")
            });
        }

        tblHistorialCompras.setModel(modelo);

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al cargar el historial de compras:\n"
                + e.getMessage(),
                "Error de base de datos",
                JOptionPane.ERROR_MESSAGE
        );
    }
}


